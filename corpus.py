"""Pairing of processed documents with their reference summaries.

Shared by the training dataset and the evaluation script so both agree on
exactly which pairs exist, and so unpaired files are reported rather than
silently dropped.
"""

from pathlib import Path
from typing import NamedTuple

SUMMARY_SUFFIX = "_summary"
PROVENANCE_FILE = "provenance.tsv"


class Corpus(NamedTuple):
    pairs: list[tuple[Path, Path]]
    documents_without_summary: list[str]
    summaries_without_document: list[str]
    # slug -> "human" | "generated", from data/summaries/provenance.tsv.
    provenance: dict[str, str]

    def origin_counts(self) -> dict[str, int]:
        counts: dict[str, int] = {}
        for doc, _ in self.pairs:
            counts[self.provenance.get(doc.stem, "unrecorded")] = (
                counts.get(self.provenance.get(doc.stem, "unrecorded"), 0) + 1
            )
        return counts

    def describe(self) -> str:
        lines = [f"{len(self.pairs)} document/summary pair(s)."]
        counts = self.origin_counts()
        if counts:
            breakdown = ", ".join(f"{n} {origin}" for origin, n in sorted(counts.items()))
            lines.append(f"  Reference summaries: {breakdown}.")
        if counts.get("generated"):
            lines.append(
                "  NOTE: some reference summaries were generated by an LLM, not "
                "written by a person. Training on them is distillation, and the "
                "model cannot be expected to exceed the generating model. See "
                "data/summaries/provenance.tsv."
            )
        if self.summaries_without_document:
            lines.append(
                "  Summaries with no matching document in this directory "
                "(not part of this corpus): "
                + ", ".join(self.summaries_without_document)
            )
        if self.documents_without_summary:
            lines.append(
                "  Documents with no summary (skipped): "
                + ", ".join(self.documents_without_summary)
            )
        return "\n".join(lines)


def load_provenance(summaries_dir) -> dict[str, str]:
    """Read slug -> origin from provenance.tsv, if present."""
    path = Path(summaries_dir) / PROVENANCE_FILE
    if not path.is_file():
        return {}
    provenance = {}
    for line in path.read_text(encoding="utf-8").splitlines()[1:]:
        fields = line.split("\t")
        if len(fields) >= 2:
            provenance[fields[0]] = fields[1]
    return provenance


def load_corpus(processed_dir, summaries_dir) -> Corpus:
    processed_dir = Path(processed_dir)
    summaries_dir = Path(summaries_dir)

    documents = {p.stem: p for p in sorted(processed_dir.glob("*.txt"))}
    summaries = {
        p.stem[: -len(SUMMARY_SUFFIX)]: p
        for p in sorted(summaries_dir.glob(f"*{SUMMARY_SUFFIX}.txt"))
    }

    paired = sorted(set(documents) & set(summaries))
    return Corpus(
        pairs=[(documents[stem], summaries[stem]) for stem in paired],
        documents_without_summary=sorted(set(documents) - set(summaries)),
        summaries_without_document=sorted(set(summaries) - set(documents)),
        provenance=load_provenance(summaries_dir),
    )
